"""Render checked-in results exclusively from saved evaluation artifacts."""

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


def report(output):
    output = Path(output)
    evaluation = json.loads((output / "evaluation.json").read_text())
    training = json.loads((output / "training.json").read_text())
    importance = pd.read_csv(output / "feature_importance.csv")
    errors = pd.read_csv(output / "scaffold_errors.csv")
    palette = {"random": "#327e9b", "scaffold": "#b85438"}
    names = list(training["splits"]["random"]["models"])
    fig, ax = plt.subplots(figsize=(9, 4.5), layout="constrained")
    for offset, kind in [(-0.16, "random"), (0.16, "scaffold")]:
        scores = [
            next(s for s in evaluation["scores"] if s["split"] == kind and s["model"] == name)
            for name in names
        ]
        point = np.array([s["rmse"] for s in scores])
        bounds = np.array([s["ci95"]["rmse"] for s in scores])
        # Percentile intervals need not contain the point estimate. Plot endpoints directly.
        positions = np.arange(len(names)) + offset
        ax.vlines(positions, bounds[:, 0], bounds[:, 1], color=palette[kind], linewidth=2)
        ax.scatter(positions, point, color=palette[kind], label=kind, zorder=3)
    ax.set_xticks(range(len(names)), [n.replace("_", " ") for n in names])
    ax.set_ylabel("Held-out RMSE (source Target units; lower is better)")
    ax.set_title("Fixed holdouts with 95% scaffold-cluster bootstrap intervals")
    ax.legend()
    ax.grid(axis="y", alpha=0.2)
    fig.savefig(output / "generalization.png", dpi=160)
    plt.close(fig)

    fig, axes = plt.subplots(1, 2, figsize=(12, 5), layout="constrained")
    for ax, kind in zip(axes, ("random", "scaffold")):
        frame = importance[importance.split == kind].sort_values("rmse_increase_mean")
        ax.barh(
            frame.feature,
            frame.rmse_increase_mean,
            xerr=frame.permutation_sd,
            color=palette[kind],
            alpha=0.85,
        )
        ax.axvline(0, color="black", linewidth=0.5)
        ax.set_title(f"{kind}: {training['splits'][kind]['winner_by_cv']}")
        ax.set_xlabel("RMSE increase on permutation (bars: repeat SD)")
    fig.savefig(output / "feature_importance.png", dpi=160)
    plt.close(fig)

    winner = training["splits"]["scaffold"]["winner_by_cv"]
    frame = errors[(errors.split == "scaffold") & (errors.model == winner)].copy()
    frame = frame.sort_values("rmse", ascending=False).head(12)
    frame["label"] = [f"S{i + 1} (n={n})" for i, n in enumerate(frame.n)]
    frame.to_csv(output / "scaffold_plot_key.csv", index=False)
    fig, ax = plt.subplots(figsize=(8, 4), layout="constrained")
    ax.barh(frame.label, frame.rmse, color=palette["scaffold"])
    ax.invert_yaxis()
    ax.set_xlabel("RMSE in source Target units")
    ax.set_title(f"Held-out scaffold errors: {winner} selected by training CV")
    fig.savefig(output / "scaffold_errors.png", dpi=160)
    plt.close(fig)

    lines = [
        "# Generated benchmark results",
        "",
        "Generated by `lnp-benchmark report`. Values are read from evaluation.json and training.json.",
        "",
        f"Dataset: {training['dataset_sha256']}. Seed: {training['seed']}. "
        f"Quick smoke run: {training['quick']}.",
        "",
        "| Split | Train / test rows | Train / test scaffolds | Shared scaffolds | CV choice |",
        "|---|---:|---:|---:|---|",
    ]
    for kind, info in training["splits"].items():
        lines.append(
            f"| {kind} | {info['train_rows']} / {info['test_rows']} | "
            f"{info['train_scaffolds']} / {info['test_scaffolds']} | "
            f"{info['shared_scaffolds']} | {info['winner_by_cv']} |"
        )
    lines += [
        "",
        "| Split | Model | RMSE (95% CI) | MAE | R² | Spearman |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for score in evaluation["scores"]:
        lo, hi = score["ci95"]["rmse"]
        rho = f"{score['spearman']:.3f}" if score["spearman"] is not None else "undefined"
        lines.append(
            f"| {score['split']} | {score['model']} | {score['rmse']:.3f} "
            f"({lo:.3f}, {hi:.3f}) | {score['mae']:.3f} | {score['r2']:.3f} | {rho} |"
        )
    lines += [
        "",
        "Positive gaps mean worse scaffold performance. The test populations differ.",
        "",
        "| Model | Scaffold minus random RMSE | 95% CI |",
        "|---|---:|---:|",
    ]
    for gap in evaluation["gaps"]:
        lo, hi = gap["ci95"]
        lines.append(
            f"| {gap['model']} | {gap['scaffold_minus_random_rmse']:.3f} | ({lo:.3f}, {hi:.3f}) |"
        )
    lines += [
        "",
        evaluation["uncertainty_scope"],
        "",
        "Gap intervals subtract independent cluster-bootstrap draws from the two holdouts. "
        "Because holdouts can overlap, these are descriptive intervals, not a paired "
        "significance test. Few test scaffold families make intervals unstable.",
        "",
        "## Scaffold error analysis",
        "",
        "The plot key maps each S label to its actual scaffold SMILES. Every family, including "
        "small ones, is in scaffold_errors.csv; small-family errors are noisy.",
        "",
        "![Generalization](generalization.png)",
        "",
        "![Permutation importance](feature_importance.png)",
        "",
        "Morgan counts are permuted as a block. Descriptor bars permute one column each. "
        "Correlated descriptors can substitute for each other; block sizes differ. "
        "Repeat SD bars are permutation variability, not confidence intervals or causal effects.",
        "",
        "![Scaffold errors](scaffold_errors.png)",
        "",
        "## Fit warnings",
        "",
    ]
    for kind, info in training["splits"].items():
        for name, model in info["models"].items():
            for warning, count in model["warnings"].items():
                lines.append(f"- {kind}/{name}: {count} occurrences of {warning}")
    lines += ["", "| Unseen scaffold | Rows | RMSE | Mean signed bias |", "|---|---:|---:|---:|"]
    for row in frame.itertuples():
        lines.append(f"| `{row.scaffold}` | {row.n} | {row.rmse:.3f} | {row.bias:+.3f} |")
    lines += ["", "Positive bias means overprediction; negative means underprediction."]
    lines += ["", "## Evaluation warnings", ""]
    lines += [f"- {message}" for message in evaluation.get("evaluation_warnings", [])]
    (output / "report.md").write_text("\n".join(lines) + "\n")
    return output / "report.md"
